// Rebuilds the story-group sections of index.html (everything after the Jesus group)
// from scripts/menu-groups.json. Run after adding games: node scripts/build-menu.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const menuFile = path.join(root, 'index.html');
const { groups } = JSON.parse(fs.readFileSync(path.join(__dirname, 'menu-groups.json'), 'utf8'));

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const html = (s) => esc(s).replace(/ · /g, ' &middot; ');

const START = '  <!-- story groups: generated by scripts/build-menu.js from scripts/menu-groups.json -->\n';
const END = '  <!-- end of story groups -->\n';

let out = START;
let count = 0;
for (const g of groups) {
  if (!g.games.length) continue;
  for (const game of g.games) {
    if (!fs.existsSync(path.join(root, game.file))) throw new Error(`${g.id}: missing ${game.file}`);
  }
  out += `\n  <section class="group" data-group="${g.id}" data-label="${esc(g.label)}" data-icon="${g.icon}">\n`;
  out += `  <h2 class="section">${esc(g.title)}</h2>\n  <p class="section-note">${esc(g.note)}</p>\n  <div class="grid">\n`;
  for (const game of g.games) {
    out += `    <a class="game" href="${game.file}">
      <div class="art" style="background: ${game.bg}">${game.art}</div>
      <h2>${esc(game.title)}</h2>
      <div class="ref">${html(game.ref)}</div>
      <p class="desc">${esc(game.desc)}</p>
      <span class="play">Play</span>
      <div class="best" data-key="${game.key}"></div>
    </a>\n`;
    count++;
  }
  out += '  </div>\n  </section>\n';
}
out += END;

let s = fs.readFileSync(menuFile, 'utf8');
const a = s.indexOf(START), b = s.indexOf(END);
if (a >= 0 && b > a) s = s.slice(0, a) + out + s.slice(b + END.length);
else {
  // First run: put the groups straight after the Jesus group.
  const anchor = '  </section>\n\n  <footer>';
  if (!s.includes(anchor)) throw new Error('could not find the end of the Jesus group in index.html');
  s = s.replace(anchor, '  </section>\n\n' + out + '\n  <footer>');
}
fs.writeFileSync(menuFile, s);
console.log(`menu: ${count} games in ${groups.filter((g) => g.games.length).length} story groups after Jesus`);
